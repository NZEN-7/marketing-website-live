/* ---- every section header lead.js emits must be known to the parser ---- */

const allForms = ["register-interest", "contact", "subscribe",
                  "basic-reserve", "founder-premium"];
const seenHeaders = new Set();
allForms.forEach((f) => {
  const body = lead.formatNotification({
    form: f, formLabel: f, name: "X Y", first_name: "X", last_name: "Y",
    email: "a@b.c", comments: "hi", drivers: ["a"], timeline: ["b"], tier: "Basic",
  }, stamp);
  (body.match(/^[A-Z][A-Z &]{3,}$/gm) || []).forEach((h) => seenHeaders.add(h.trim()));
});
const unknown = [...seenHeaders].filter((h) => LEAD_SECTIONS.indexOf(h) === -1);
if (unknown.length) {
  failures++;
  console.log(`FAIL  section headers not known to the parser: ${unknown.join(", ")}`);
  console.log(`        add them to LEAD_SECTIONS, or the field before each one`);
  console.log(`        will silently absorb the header into its value.`);
} else {
  console.log(`ok    all ${seenHeaders.size} section headers known to the parser`);
}

/* ---- the CSV round-trip, because column 4 is the dedupe key ---- */

{
  // A comment containing a comma and a quote is the case that shifts columns
  // and makes readMessageIds_ read the wrong field: leads then duplicate on
  // every run, or stop being recognised at all.
  const row = ["ab12cd34", "2026-08-24T09:00:00+10:00", "2026-08-24T08:58:00+10:00",
               "199abc0def", "Contact Form", "freevolt",
               'Hi, "quoted", and, commas'].map(capture.csvCell_).join(",");
  const back = capture.csvRow_(row);
  if (back[3] !== "199abc0def" || back[6] !== 'Hi, "quoted", and, commas') {
    failures++;
    console.log("FAIL  csv round-trip");
    console.log(`        gmail_message_id: ${JSON.stringify(back[3])}`);
    console.log(`        last column:      ${JSON.stringify(back[6])}`);
  } else {
    console.log("ok    csv round-trip survives commas and quotes");
  }
}

// The capture query must accept both senders while api/lead.js moves from
// Nick's mailbox to noreply@ (keys plan, 27 Sep 2026). Dropping either one
// stops lead capture with no error, which is the failure this file exists for.
{
  const gs = require("fs").readFileSync(require("path").join(__dirname, "apps-script", "lead-capture.gs"), "utf8");
  const q = (gs.match(/QUERY:\s*'([^']*)'/) || [])[1] || "";
  if (q.includes("nickz@thermaldawn.com") && q.includes("noreply@thermaldawn.com")) {
    console.log("ok    capture query accepts both senders (nickz@ and noreply@)");
  } else {
    console.log("FAIL  capture query must list both nickz@ and noreply@: " + q);
    failures++;
  }
}

console.log();
if (failures) {
  console.log(`${failures} sample(s) failed. If a label changed in ` +
              `api/lead.js, update LEAD_LABELS in scripts/apps-script/` +
              `lead-parser.gs and re-paste it into the Apps Script project.`);
  process.exit(1);
}
console.log("All parser checks passed.");
