/* Round-trips the notification emails through the Apps Script parser.

     npm run test:parser

   The point: api/lead.js WRITES these emails and the CRM's Apps Script READS
   them. Nothing in either file knows about the other, so a field label renamed
   on the website would break lead capture in Google Drive with no error, and
   the first sign would be a quiet week in the CRM.

   This closes that loop. Every sample below is generated by api/lead.js
   itself, then parsed, then checked field by field. Rename a label in
   formatNotification() and this fails immediately.

   The Wix sample has the exact layout of a real notification of
   18 Aug 2026, with the identity replaced; it exercises the two things the parser
   exists to survive: one run-on line, and List(...) around a multi-select.
*/
"use strict";

const path = require("path");
const lead = require("../api/lead.js");
const { parseLead, LEAD_SECTIONS } = require(path.join(__dirname, "apps-script", "lead-parser.gs"));
const capture = require(path.join(__dirname, "apps-script", "lead-capture.gs"));

let failures = 0;

function check(name, body, expected) {
  const got = parseLead(body);
  const bad = Object.keys(expected).filter((k) => got[k] !== expected[k]);
  if (bad.length) {
    failures++;
    console.log(`FAIL  ${name}`);
    bad.forEach((k) =>
      console.log(`        ${k}\n          expected: ${JSON.stringify(expected[k])}` +
                  `\n          got:      ${JSON.stringify(got[k])}`));
  } else {
    console.log(`ok    ${name}  (${Object.keys(expected).length} fields)`);
  }
}

